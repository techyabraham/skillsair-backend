#!/usr/bin/env node
/**
 * Writes the SkillsAir Studio theme from scripts/admin-theme.config.mjs:
 *   src/app/(payload)/styles/tokens.css  --sa-* semantic tokens (light and dark)
 *   src/app/(payload)/styles/theme.css   Payload's colour variables mapped onto the brand
 * Both go in `@layer payload`, which Payload declares after `payload-default`, so they win
 * over Payload's defaults and stay overridable by unlayered CSS.
 *
 * Usage: node scripts/generate-admin-theme.mjs
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { ramp } from './admin-color.mjs'
import { elevation, semantic, SEMANTIC_STEPS, STEPS, surfaces, tokens } from './admin-theme.config.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const stylesDir = path.join(root, 'src', 'app', '(payload)', 'styles')
const header = (what) => `/* GENERATED by scripts/generate-admin-theme.mjs from scripts/admin-theme.config.mjs. Do not edit by hand. */\n/* ${what} */\n`

export function buildTheme() {
  const light = ramp(elevation.light, STEPS)
  const dark = ramp(elevation.dark, STEPS)
  const semanticRamps = Object.fromEntries(Object.entries(semantic).map(([name, anchors]) => [name, ramp(anchors, SEMANTIC_STEPS)]))
  return { light, dark, semanticRamps }
}

function themeCss() {
  const { light, dark, semanticRamps } = buildTheme()
  const lines = [header('Payload theme variables mapped onto the SkillsAir brand (light and dark).'), '@layer payload {', '  :root {']
  for (const step of STEPS) lines.push(`    --color-base-${step}: ${light[step]};`)
  for (const [name, values] of Object.entries(semanticRamps)) {
    for (const step of SEMANTIC_STEPS) lines.push(`    --color-${name}-${step}: ${values[step]};`)
  }
  for (const step of STEPS) lines.push(`    --theme-elevation-${step}: ${light[step]};`)
  for (const [name, value] of Object.entries(surfaces.light)) lines.push(`    ${name}: ${value};`)
  lines.push('    --theme-border-color: var(--theme-elevation-150);')
  lines.push('  }', '', "  html[data-theme='dark'] {")
  for (const step of STEPS) lines.push(`    --theme-elevation-${step}: ${dark[step]};`)
  for (const [name, value] of Object.entries(surfaces.dark)) lines.push(`    ${name}: ${value};`)
  lines.push('    --theme-border-color: var(--theme-elevation-150);')
  lines.push('  }', '}', '')
  return lines.join('\n')
}

function tokensCss() {
  const block = (values) => Object.entries(values).map(([name, value]) => `    --sa-${name}: ${value};`).join('\n')
  return `${header('SkillsAir Studio semantic tokens. Components use these, never raw hex.')}@layer payload {
  :root {
${block(tokens.light)}
    --sa-focus-ring: 0 0 0 3px var(--sa-focus-inner), 0 0 0 4px var(--sa-focus-outer);
    --sa-shadow-1: 0 1px 2px rgb(13 27 75 / 0.06), 0 1px 1px rgb(13 27 75 / 0.04);
    --sa-shadow-2: 0 8px 24px rgb(13 27 75 / 0.08);
    --sa-font-display: 'Space Grotesk', var(--font-body);
    --sa-radius-pill: 999px;
  }

  html[data-theme='dark'] {
${block(tokens.dark)}
    --sa-shadow-1: none;
    --sa-shadow-2: none;
  }
}
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  writeFileSync(path.join(stylesDir, 'theme.css'), themeCss())
  writeFileSync(path.join(stylesDir, 'tokens.css'), tokensCss())
  console.log('Wrote styles/theme.css and styles/tokens.css')
}
